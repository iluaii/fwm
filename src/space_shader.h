    "        vec3 g = STAR_COL * gk * (2.0 * exp(-x / (angS * 0.35 + 0.003))\n"
    "                                  + 0.10 * exp(-ang * 6.0)\n"
    "                                  + 0.015 / (1.0 + ang * ang * 60.0));\n"
    "        vec3 sv = vec3(dot(sd, uRight), dot(sd, uUp), dot(sd, uFwd));\n"
    "        if (sv.z > 0.05) {\n"
    "            vec2 s2 = sv.xy / (sv.z * uTanHalf);\n"
    "            vec2 d = uv - s2;\n"
    "            float spk = 0.0;\n"
    "            for (int k = 0; k < 3; k++) {\n"
    "                float a = 0.35 + float(k) * PI / 3.0;\n"
    "                vec2 dir = vec2(cos(a), sin(a));\n"
    "                float perp = abs(dot(d, vec2(-dir.y, dir.x)));\n"
    "                float along = abs(dot(d, dir));\n"
    "                spk += exp(-perp / 0.0014) * exp(-along * 9.0);\n"
    "            }\n"
    "            g += STAR_COL * spk * 0.5 * gk * (stT == 3 || stT == 4 ? 2.0 : 1.0) * (stT == 5 ? 0.0 : 1.0);\n"
    "        }\n"
    "        // вспышка смены звезды — не зависит от вида: у дыры своего блика нет\n"
    "        g += STAR_COL * uStarFlash * (4.0 * exp(-ang * 14.0) + 0.5 * exp(-ang * 3.0));\n"
    "        col += g * vis;\n"
    "    }\n"
    "\n"
    "    col = aces(col * uExposure);\n"
    "    col = pow(col, vec3(1.0 / 2.2));\n"
    "    col += (hash13(vec3(gl_FragCoord.xy, fract(uTime) * 100.0)) - 0.5) / 255.0;\n"
    "    gl_FragColor = vec4(col, 1.0);\n"
    "}\n";

